#!/usr/bin/env bash
# cat-s9a2: live verification of Cloud Run + Secret Manager behaviour (follow-up of the cat-jqhh spike).
#
# Answers, for a Cloud Run SERVICE, JOB and WORKER POOL (REQ-001..003):
#   E1  the same key in --env-vars-file and --set-secrets: error, or which one wins?
#   E2  a key removed from the YAML file on redeploy: is it removed from the revision?
#   E3  --set-secrets idempotence: does it replace ALL secrets of the revision?
#   E4  ENV=SECRET:N is pinned, ENV=SECRET:latest is resolved at instance start (job execution)
#   E5  disabled / destroyed pinned version: failure mode (deploy time vs. start time)
#   E6  worker pools: is the secret flag supported at all?
#
# Usage:   VERIFY_PROJECT=<gcp-project-id> bash docs/spikes/cat-s9a2-verify.sh
# Needs:   gcloud (authenticated, with the Cloud Run + Secret Manager + Logging APIs enabled in the project;
#          roles to create services/jobs/worker pools/secrets and to grant secretAccessor to the runtime SA),
#          python3, openssl (optional).
# Creates: only throwaway resources named s9a2-<run id>-*; ALL of them are deleted by the EXIT trap.
# Output:  a sanitized log file (path printed at start and end). Secret values are random, generated here, never
#          printed; any value, API key or key material is masked before it reaches the log.
#
# The script requires exactly one environment variable (VERIFY_PROJECT; TMPDIR is optional). Everything else is a constant below.
# Not for production projects: it deploys public sample images and briefly runs a job.

set -u
set -o pipefail

if [ -z "${VERIFY_PROJECT:-}" ]; then
  echo "VERIFY_PROJECT is not set. Usage: VERIFY_PROJECT=<gcp-project-id> bash $0" >&2
  echo "Use a throwaway/sandbox project: this script creates and deletes Cloud Run resources and secrets." >&2
  exit 2
fi

PROJECT="$VERIFY_PROJECT"
REGION="europe-west1"
IMG_SERVICE="us-docker.pkg.dev/cloudrun/container/hello"
IMG_JOB="gcr.io/google.com/cloudsdktool/google-cloud-cli:slim"
# worker pools need a long-running non-HTTP container; the job image with a sleep command is enough to deploy
IMG_WORKER="$IMG_JOB"

RUN_ID="$(date +%m%d%H%M)$(printf '%04d' $((RANDOM % 10000)))"
P="s9a2-$RUN_ID"
LOG="${TMPDIR:-/tmp}/cat-s9a2-verify-$RUN_ID.log"
SED_FILE="$(mktemp)"
WORK_DIR="$(mktemp -d)"
CREATED=() # entries "kind:name", kind in service|job|workerpool|secret

# ---------------------------------------------------------------- logging / sanitizing

# mask anything that looks like a credential, plus every secret value generated by this run
add_mask() { printf 's/%s/***VALUE***/g\n' "$1" >>"$SED_FILE"; }
sanitize() {
  sed -E \
    -e 's/AI''za[0-9A-Za-z_-]{20,}/***APIKEY***/g' \
    -e 's/ya29\.[0-9A-Za-z_-]+/***TOKEN***/g' \
    -e '/-----''BEGIN/,/-----''END/d' \
    -e 's/("?private''_key[a-z_]*"?[ :=]+).*/\1***REDACTED***/' \
    -e 's/(Bearer )[0-9A-Za-z._-]+/\1***TOKEN***/g' |
    sed -f "$SED_FILE"
}
log() { printf '%s\n' "$*" | sanitize | tee -a "$LOG"; }
section() { log ""; log "=================== $* ==================="; }

# run <label> <cmd...>: log the command and its sanitized output, return the command's exit code
run() {
  local label="$1"
  shift
  log ""
  log "--- $label"
  log "\$ $*"
  local rc
  "$@" >"$WORK_DIR/out.txt" 2>&1 # no subshell: deploy() records CREATED entries
  rc=$?
  [ -s "$WORK_DIR/out.txt" ] && sanitize <"$WORK_DIR/out.txt" | tee -a "$LOG"
  log "[exit $rc]"
  return $rc
}

rand_value() { openssl rand -hex 12 2>/dev/null || printf '%s%s%s' "$RANDOM" "$RANDOM" "$RANDOM"; }
short_hash() { printf '%s' "$1" | { sha256sum 2>/dev/null || shasum -a 256; } | cut -c1-16; }

# ---------------------------------------------------------------- cleanup (always)

cleanup() {
  local rc=$?
  trap - EXIT INT TERM
  set +e
  log ""
  section "cleanup: deleting every resource created by this run (prefix $P)"
  local entry kind name
  # reverse order: workloads before the secrets they reference
  for ((i = ${#CREATED[@]} - 1; i >= 0; i--)); do
    entry="${CREATED[$i]}"
    kind="${entry%%:*}"
    name="${entry#*:}"
    case "$kind" in
      service) gcloud run services delete "$name" --project="$PROJECT" --region="$REGION" --quiet >>"$LOG" 2>&1 ;;
      job) gcloud run jobs delete "$name" --project="$PROJECT" --region="$REGION" --quiet >>"$LOG" 2>&1 ;;
      workerpool) gcloud beta run worker-pools delete "$name" --project="$PROJECT" --region="$REGION" --quiet >>"$LOG" 2>&1 ;;
    esac
  done
  # sweep by prefix: also catches secrets (created inside $(...) subshells, so not recorded) and half-created resources
  local n
  for n in $(gcloud run services list --project="$PROJECT" --region="$REGION" --format='value(name)' 2>/dev/null | grep "^$P-"); do
    gcloud run services delete "$n" --project="$PROJECT" --region="$REGION" --quiet >>"$LOG" 2>&1
  done
  for n in $(gcloud run jobs list --project="$PROJECT" --region="$REGION" --format='value(name)' 2>/dev/null | grep "^$P-"); do
    gcloud run jobs delete "$n" --project="$PROJECT" --region="$REGION" --quiet >>"$LOG" 2>&1
  done
  for n in $(gcloud beta run worker-pools list --project="$PROJECT" --region="$REGION" --format='value(name)' 2>/dev/null | grep "^$P-"); do
    gcloud beta run worker-pools delete "$n" --project="$PROJECT" --region="$REGION" --quiet >>"$LOG" 2>&1
  done
  for n in $(gcloud secrets list --project="$PROJECT" --format='value(name.basename())' 2>/dev/null | grep "^$P-"); do
    gcloud secrets delete "$n" --project="$PROJECT" --quiet >>"$LOG" 2>&1
  done
  # report what is left, so a failed cleanup is visible
  log "remaining (must be empty):"
  {
    gcloud run services list --project="$PROJECT" --region="$REGION" --format='value(name)' 2>/dev/null | grep "^$P-"
    gcloud run jobs list --project="$PROJECT" --region="$REGION" --format='value(name)' 2>/dev/null | grep "^$P-"
    gcloud beta run worker-pools list --project="$PROJECT" --region="$REGION" --format='value(name)' 2>/dev/null | grep "^$P-"
    gcloud secrets list --project="$PROJECT" --format='value(name.basename())' 2>/dev/null | grep "^$P-"
  } | sanitize | tee -a "$LOG"
  rm -rf "$WORK_DIR" "$SED_FILE"
  echo "log: $LOG"
  exit $rc
}
trap cleanup EXIT INT TERM

# ---------------------------------------------------------------- secrets

# new_secret <suffix> -> creates secret $P-<suffix> with version 1; prints the secret name
new_secret() {
  local name="$P-$1" value
  value="$(rand_value)"
  add_mask "$value"
  printf '%s' "$value" | gcloud secrets create "$name" --project="$PROJECT" --replication-policy=automatic --data-file=- >>"$LOG" 2>&1 || return 1
  CREATED+=("secret:$name")
  echo "$name"
}
# add_version <secret> -> prints the new random value's short hash (the value itself is never printed)
add_version() {
  local value
  value="$(rand_value)"
  add_mask "$value"
  printf '%s' "$value" | gcloud secrets versions add "$1" --project="$PROJECT" --data-file=- >>"$LOG" 2>&1 || return 1
  short_hash "$value"
}
# value_hash <secret> <version> -> short hash of that version's value, for comparing with the job's output
value_hash() {
  local v
  v="$(gcloud secrets versions access "$2" --secret="$1" --project="$PROJECT" 2>/dev/null)" || return 1
  short_hash "$v"
}
grant_accessor() { # <secret>: the default compute SA is the runtime identity of everything created here
  local num sa
  num="$(gcloud projects describe "$PROJECT" --format='value(projectNumber)' 2>/dev/null)"
  sa="${num}-compute@developer.gserviceaccount.com"
  gcloud secrets add-iam-policy-binding "$1" --project="$PROJECT" \
    --member="serviceAccount:$sa" --role=roles/secretmanager.secretAccessor >>"$LOG" 2>&1
}

# ---------------------------------------------------------------- generic workload helpers

COMMON=(--project="$PROJECT" --region="$REGION" --quiet)
JOB_SCRIPT='for v in LATEST PIN; do eval "x=\${$v-unset}"; printf "RESULT %s sha256=%s\n" "$v" "$(printf %s "$x" | sha256sum | cut -c1-16)"; done'

# deploy <kind> <name> <extra gcloud args...>
deploy() {
  local kind="$1" name="$2"
  shift 2
  case "$kind" in
    service)
      CREATED+=("service:$name")
      gcloud run deploy "$name" --image="$IMG_SERVICE" --no-allow-unauthenticated --max-instances=1 "${COMMON[@]}" "$@" ;;
    job)
      CREATED+=("job:$name")
      gcloud run jobs deploy "$name" --image="$IMG_JOB" --command=sh --args="^@^-c@$JOB_SCRIPT" --max-retries=0 "${COMMON[@]}" "$@" ;;
    workerpool)
      CREATED+=("workerpool:$name")
      gcloud beta run worker-pools deploy "$name" --image="$IMG_WORKER" --command=sleep --args=3600 --instances=1 "${COMMON[@]}" "$@" ;;
  esac
}
# describe_env <kind> <name>: one line per env var: NAME=plain value | NAME=secret:<name>:<version>
describe_env() {
  local kind="$1" name="$2" cmd
  case "$kind" in
    service) cmd=(gcloud run services describe "$name") ;;
    job) cmd=(gcloud run jobs describe "$name") ;;
    workerpool) cmd=(gcloud beta run worker-pools describe "$name") ;;
  esac
  "${cmd[@]}" --project="$PROJECT" --region="$REGION" --format=json 2>&1 | python3 -c '
import json, sys
try:
    doc = json.load(sys.stdin)
except Exception as e:
    print("could not parse describe output: %s" % e); sys.exit(0)
def walk(o):
    if isinstance(o, dict):
        if isinstance(o.get("containers"), list):
            for c in o["containers"]:
                for e in c.get("env", []) or []:
                    ref = (e.get("valueSource") or {}).get("secretKeyRef")
                    print("  %s=%s" % (e.get("name"), ("secret:%s:%s" % (ref.get("secret"), ref.get("version"))) if ref else ("plain:" + str(e.get("value")))))
        for v in o.values(): walk(v)
    elif isinstance(o, list):
        for v in o: walk(v)
print("env of revision/template:")
walk(doc)
' 2>&1 | sanitize | tee -a "$LOG"
}
yaml_file() { # <file> <KEY=value>...
  local f="$1"
  shift
  : >"$f"
  local kv
  for kv in "$@"; do printf '%s: "%s"\n' "${kv%%=*}" "${kv#*=}" >>"$f"; done
}

# ---------------------------------------------------------------- experiments

experiments_for() {
  local kind="$1" n="$P-${1:0:3}" # short name prefix per kind: ser / job / wor
  section "$kind"

  local s1 s2
  s1="$(new_secret "$kind-a")" || { log "could not create secret, skipping $kind"; return; }
  s2="$(new_secret "$kind-b")" || { log "could not create secret, skipping $kind"; return; }
  grant_accessor "$s1"
  grant_accessor "$s2"

  # E1 ---------------------------------------------------------
  log ""
  log "### E1 ($kind): same key DUP in --env-vars-file and --set-secrets"
  yaml_file "$WORK_DIR/e1.yaml" DUP=plain-from-yaml
  run "E1 deploy with DUP in both" deploy "$kind" "$n-e1" --env-vars-file="$WORK_DIR/e1.yaml" --set-secrets="DUP=$s1:1" &&
    describe_env "$kind" "$n-e1"
  log "E1 result: a non-zero exit above = gcloud/API rejects the duplicate; otherwise the env list above shows the winner"

  # E2 ---------------------------------------------------------
  log ""
  log "### E2 ($kind): key removed from the YAML file on redeploy"
  yaml_file "$WORK_DIR/e2a.yaml" KEEP=1 DROP=1
  yaml_file "$WORK_DIR/e2b.yaml" KEEP=1
  run "E2 first deploy (KEEP, DROP)" deploy "$kind" "$n-e2" --env-vars-file="$WORK_DIR/e2a.yaml"
  run "E2 redeploy with --env-vars-file lacking DROP" deploy "$kind" "$n-e2" --env-vars-file="$WORK_DIR/e2b.yaml"
  describe_env "$kind" "$n-e2"
  log "E2 result: DROP still present => --env-vars-file only merges; a --remove-env-vars/--clear-env-vars step is needed"
  # variant: moving a plain key to a secret (the migration case from the spike)
  yaml_file "$WORK_DIR/e2c.yaml" KEEP=1
  run "E2b redeploy moving DROP to a secret (file lacks DROP, --set-secrets adds it)" deploy "$kind" "$n-e2" --env-vars-file="$WORK_DIR/e2c.yaml" --set-secrets="DROP=$s1:1"
  describe_env "$kind" "$n-e2"

  # E3 ---------------------------------------------------------
  log ""
  log "### E3 ($kind): --set-secrets idempotence / replace semantics"
  run "E3 deploy with two secrets S1,S2" deploy "$kind" "$n-e3" --set-secrets="S1=$s1:1,S2=$s2:1"
  describe_env "$kind" "$n-e3"
  run "E3 redeploy, same flags (no change expected)" deploy "$kind" "$n-e3" --set-secrets="S1=$s1:1,S2=$s2:1"
  describe_env "$kind" "$n-e3"
  run "E3 redeploy with --set-secrets naming only S1" deploy "$kind" "$n-e3" --set-secrets="S1=$s1:1"
  describe_env "$kind" "$n-e3"
  log "E3 result: S2 gone after the last redeploy => --set-secrets replaces ALL secrets (idempotent); S2 kept => it merges"

  # E5 ---------------------------------------------------------
  log ""
  log "### E5 ($kind): disabled / destroyed pinned version"
  local h2
  h2="$(add_version "$s1")" && log "added version 2 of $s1 (value hash $h2)"
  run "E5 deploy pinned to version 1 (baseline)" deploy "$kind" "$n-e5" --set-secrets="PIN=$s1:1"
  run "E5 disable version 1" gcloud secrets versions disable 1 --secret="$s1" --project="$PROJECT" --quiet
  run "E5 deploy pinned to the DISABLED version 1 (deploy-time failure expected)" deploy "$kind" "$n-e5-dis" --set-secrets="PIN=$s1:1"
  run "E5 redeploy of the existing workload (env change forces a new revision/execution template)" deploy "$kind" "$n-e5" --set-secrets="PIN=$s1:1" --update-env-vars=BUMP=disabled
  [ "$kind" = job ] && run "E5 execute job with a DISABLED pinned version (start-time failure expected)" gcloud run jobs execute "$n-e5" "${COMMON[@]}" --wait
  run "E5 re-enable version 1" gcloud secrets versions enable 1 --secret="$s1" --project="$PROJECT" --quiet
  run "E5 disable + destroy version 1" gcloud secrets versions destroy 1 --secret="$s1" --project="$PROJECT" --quiet
  run "E5 deploy pinned to the DESTROYED version 1" deploy "$kind" "$n-e5-des" --set-secrets="PIN=$s1:1"
  run "E5 redeploy of the existing workload after destroy" deploy "$kind" "$n-e5" --set-secrets="PIN=$s1:1" --update-env-vars=BUMP=destroyed
  [ "$kind" = job ] && run "E5 execute job with a DESTROYED pinned version" gcloud run jobs execute "$n-e5" "${COMMON[@]}" --wait
  run "E5 status of the pre-existing workload" describe_env "$kind" "$n-e5"
  log "E5 result: look at WHEN each command failed (deploy vs. execute) and whether the previously deployed revision keeps running"
}

experiment_pinning_latest() {
  section "E4 job: ENV=SECRET:N is pinned, ENV=SECRET:latest is resolved at instance start"
  local s name h1 h2 got
  s="$(new_secret e4)" || { log "could not create secret, skipping E4"; return; }
  grant_accessor "$s"
  name="$P-e4"
  h1="$(value_hash "$s" 1)"
  run "E4 deploy job with LATEST=$s:latest and PIN=$s:1" deploy job "$name" --set-secrets="LATEST=$s:latest,PIN=$s:1"
  h2="$(add_version "$s")"
  log "version 1 value hash: $h1   version 2 value hash: $h2"
  run "E4 execute job after version 2 was added (no redeploy)" gcloud run jobs execute "$name" "${COMMON[@]}" --wait
  log "waiting for logs (up to ~2 min)..."
  local try
  for try in 1 2 3 4 5 6; do
    got="$(gcloud logging read "resource.type=cloud_run_job AND resource.labels.job_name=$name AND textPayload:RESULT" \
      --project="$PROJECT" --freshness=30m --limit=10 --format='value(textPayload)' 2>/dev/null)"
    [ -n "$got" ] && break
    sleep 20
  done
  log "job output (hashes only):"
  log "$got"
  log "E4 expectation: LATEST sha256=$h2 (resolved at instance start), PIN sha256=$h1 (pinned)"
  case "$got" in
    *"LATEST sha256=$h2"*) log "E4 LATEST: resolved at instance start (MATCH)" ;;
    *) log "E4 LATEST: did NOT resolve to version 2 (see output above)" ;;
  esac
  case "$got" in
    *"PIN sha256=$h1"*) log "E4 PIN: stayed on version 1 (MATCH)" ;;
    *) log "E4 PIN: did NOT stay on version 1 (see output above)" ;;
  esac
  describe_env job "$name"
}

experiment_worker_pool_flags() {
  section "E6 worker pool: secret flag support"
  log "\$ gcloud beta run worker-pools deploy --help | grep -E -- '--(set|update|remove|clear)-secrets'"
  gcloud beta run worker-pools deploy --help 2>&1 | grep -E -- '--(set|update|remove|clear)-secrets' | sanitize | tee -a "$LOG"
  log "E6 result: no flag listed above => worker pools cannot take --set-secrets via gcloud (E1-E3 worker pool sections show the real deploy outcome)"
}

# ---------------------------------------------------------------- main

log "cat-s9a2 verification, run $RUN_ID, project $PROJECT, region $REGION"
log "log file: $LOG"
log "gcloud: $(gcloud --version 2>/dev/null | head -1)"
if ! gcloud projects describe "$PROJECT" --format='value(projectId)' >/dev/null 2>&1; then
  log "cannot access project $PROJECT with the current gcloud credentials; aborting"
  exit 1
fi
run "enable required APIs" gcloud services enable run.googleapis.com secretmanager.googleapis.com logging.googleapis.com --project="$PROJECT"

experiment_worker_pool_flags
experiments_for service
experiments_for job
experiments_for workerpool
experiment_pinning_latest

section "done"
log "Fill the findings into the spike doc; the cleanup trap now removes every resource."
